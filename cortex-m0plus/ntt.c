static inline int32_t barrett_mul_approx(int32_t a, int32_t b, int32_t bp)
{
    const int64_t hi = ((int64_t)a * bp) >> 32;
    return (int32_t)((int64_t)a * b - hi * Q);
}

static inline int32_t barrett_freeze(int32_t a)
{
    int64_t t = (int64_t)a * QREC;
    t >>= 32;
    t = a - t * Q;             /* -2Q < t < 2Q */
    t += (t >> 31) & DQ;       /* 0 <= t < 2Q */
    t -= ~((t - Q) >> 31) & Q; /* 0 <= t < Q */
    return (int32_t)t;
}

/*************************************************
 * Name:        ntt
 *
 * Description: Forward NTT, in-place. No modular reduction is performed after
 *              additions or subtractions. Output vector is in bitreversed
 *              order.
 *
 * Arguments:   - int32_t a[N]: input/output coefficient array
 **************************************************/
void ntt(int32_t a[N])
{
    unsigned int len, start, j, k;
    int32_t zeta, zetap, t;

    k = 0;
    for (len = 128; len > 0; len >>= 1) {
        for (start = 0; start < N; start = j + len) {
            zeta = (int32_t)READ_DWORD(zetas_barrett[++k][0]);
            zetap = (int32_t)READ_DWORD(zetas_barrett[k][1]);
            for (j = start; j < start + len; ++j) {
                t = barrett_mul_approx(a[j + len], zeta, zetap);
                a[j + len] = a[j] - t;
                a[j] = a[j] + t;
            }
        }
    }
}

/*************************************************
 * Name:        invntt_tomont
 *
 * Description: Inverse NTT and multiplication by Montgomery factor 2^32.
 *              In-place. No modular reductions after additions or
 *              subtractions. Output coefficients are standard representatives.
 *
 * Arguments:   - int32_t a[N]: input/output coefficient array
 **************************************************/
void invntt_tomont(int32_t a[N])
{
    unsigned int start, len, j, k;
    int32_t t, zeta, zetap;

    k = 256;
    for (len = 1; len < N; len <<= 1) {
        for (start = 0; start < N; start = j + len) {
            --k;
            zeta = -(int32_t)READ_DWORD(zetas_barrett[k][0]);
            zetap = -(int32_t)READ_DWORD(zetas_barrett[k][1]);
            for (j = start; j < start + len; ++j) {
                t = a[j];
                a[j] = t + a[j + len];
                a[j + len] = t - a[j + len];
                a[j + len] = barrett_mul_approx(a[j + len], zeta, zetap);
            }
        }
    }

    for (j = 0; j < N; ++j) {
        a[j] = barrett_freeze(barrett_mul_approx(
            a[j], INV_N_MONT_CENTERED, INV_N_MONT_BP));
    }
}

